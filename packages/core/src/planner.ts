// Hamilton planner (M2) — deterministic graph validation/projection plus
// LLM-assisted decomposition with zod-validated structured output.
// The only planner-owned module in Core (HAMILTON.md §"Planning").

import { readFileSync } from "node:fs"
import { getLogger } from "@logtape/logtape"
import { taskGraphSchema } from "@hamilton/shared"
import type { Task, TaskGraph } from "@hamilton/shared"
import type { ModelRef } from "@opencode-ai/sdk/v2"
import type { ControlPlane } from "./opencode.ts"

const logger = getLogger(["hamilton", "core", "planner"])

// ---------------------------------------------------------------------------
// 1. Deterministic graph validation
// ---------------------------------------------------------------------------

export type ValidateGraphResult =
  | { ok: true; graph: TaskGraph }
  | { ok: false; issues: string[] }

export function validateGraph(value: unknown): ValidateGraphResult {
  const parsed = taskGraphSchema.safeParse(value)
  if (!parsed.success) {
    return {
      ok: false,
      issues: parsed.error.issues.map((issue) => {
        let path = ""
        for (const part of issue.path) {
          const name = typeof part === "symbol" ? String(part) : part
          if (typeof name === "number") path += `[${name}]`
          else path += path === "" ? name : `.${name}`
        }
        return `${path || "<root>"}: ${issue.message}`
      }),
    }
  }
  const graph = parsed.data
  const issues: string[] = []

  const ids = new Set(graph.tasks.map((task) => task.id))
  for (const task of graph.tasks) {
    for (const dep of task.depends_on) {
      if (!ids.has(dep)) {
        issues.push(`task ${task.id}: depends on missing task '${dep}'`)
      }
    }
  }

  for (const cycle of findCycles(graph.tasks)) {
    issues.push(`cycle: ${cycle.join(" -> ")}`)
  }

  if (issues.length > 0) return { ok: false, issues }
  return { ok: true, graph }
}

// DFS over depends_on; every cycle is reported once, as the path that closes it.
function findCycles(tasks: Task[]): string[][] {
  const byId = new Map(tasks.map((task) => [task.id, task] as const))
  const cycles: string[][] = []
  const seen = new Set<string>()
  const visited = new Set<string>()
  const onStack = new Set<string>()
  const stack: string[] = []

  const walk = (id: string): void => {
    if (visited.has(id)) return
    if (onStack.has(id)) {
      const path = [...stack.slice(stack.indexOf(id)), id]
      const key = path.join("|")
      if (!seen.has(key)) {
        seen.add(key)
        cycles.push(path)
      }
      return
    }
    onStack.add(id)
    stack.push(id)
    for (const dep of byId.get(id)?.depends_on ?? []) {
      if (byId.has(dep)) walk(dep)
    }
    stack.pop()
    onStack.delete(id)
    visited.add(id)
  }

  for (const task of tasks) walk(task.id)
  return cycles
}

// Minimal normalization: only assign a branch when missing. Statuses, contracts
// and optional fields are left exactly as validated.
export function normalizeGraph(graph: TaskGraph): TaskGraph {
  return {
    ...graph,
    tasks: graph.tasks.map((task) =>
      task.branch === undefined ? { ...task, branch: `feat/${task.id}` } : task,
    ),
  }
}

// ---------------------------------------------------------------------------
// 2. graph.yaml projection (deterministic, no external YAML dependency)
// ---------------------------------------------------------------------------

const YAML_PLAIN_SAFE = /^[a-zA-Z0-9_./\s-]+$/
const YAML_LOOKS_SCALAR = /^-?\d+(\.\d+)?$|^(true|false|null)$/

function yamlScalar(value: string): string {
  if (value === "") return '""'
  if (
    value !== value.trim() ||
    !YAML_PLAIN_SAFE.test(value) ||
    YAML_LOOKS_SCALAR.test(value)
  ) {
    return `"${value.replace(/"/g, '\\"')}"`
  }
  return value
}

// Contract strings are natural-language references; quote them unconditionally.
function yamlContractItem(value: string): string {
  return `"${value.replace(/"/g, '\\"')}"`
}

function yamlList(items: string[], indent: number): string {
  if (items.length === 0) return " []"
  const pad = " ".repeat(indent)
  return `\n${items.map((item) => `${pad}- ${item}`).join("\n")}`
}

// graph.yaml is a projection of the task graph for the conductor and agents;
// the canonical machine-readable plan stays JSON (see planFromFile).
export function renderGraphYaml(graph: TaskGraph): string {
  const lines = ["# Task DAG — generated by Hamilton planner (M2)", "tasks:"]
  for (const task of graph.tasks) {
    lines.push(`  - id: ${yamlScalar(task.id)}`)
    lines.push(`    role: ${yamlScalar(task.role)}`)
    lines.push(`    zone:${yamlList(task.zone.map(yamlScalar), 6)}`)
    lines.push(`    depends_on:${yamlList(task.depends_on.map(yamlScalar), 6)}`)
    lines.push(`    status: ${yamlScalar(task.status)}`)
    lines.push(`    on_failure: ${yamlScalar(task.on_failure)}`)
    lines.push(`    contract:`)
    lines.push(
      `      inputs:${yamlList(task.contract.inputs.map(yamlContractItem), 8)}`,
    )
    lines.push(
      `      outputs:${yamlList(task.contract.outputs.map(yamlContractItem), 8)}`,
    )
    lines.push(`    model: ${yamlScalar(task.model)}`)
    lines.push(
      `    allowed_subagents:${yamlList(task.allowed_subagents.map(yamlScalar), 6)}`,
    )
    if (task.budget_cap !== undefined) {
      lines.push(`    budget_cap: ${task.budget_cap}`)
    }
    if (task.branch !== undefined) {
      lines.push(`    branch: ${yamlScalar(task.branch)}`)
    }
    if (task.pr_title !== undefined) {
      lines.push(`    pr_title: ${yamlScalar(task.pr_title)}`)
    }
  }
  return `${lines.join("\n")}\n`
}

// ---------------------------------------------------------------------------
// 3. Agent brief generation (deterministic markdown)
// ---------------------------------------------------------------------------

export interface BriefContext {
  repoRoot: string
  parent: string
  worktreePath: string
}

function firstOutputWord(contract: { outputs: string[] }): string {
  const first = contract.outputs[0]
  if (first === undefined) return "task"
  return first.trim().split(/\s+/)[0] ?? "task"
}

export function renderBrief(task: Task, ctx: BriefContext): string {
  const branch = task.branch ?? `feat/${task.id}`
  const prTitle =
    task.pr_title ?? `feat(${task.id}): ${firstOutputWord(task.contract)}`
  const zoneLines =
    task.zone.length > 0
      ? task.zone.map((entry) => `  - \`${entry}\``).join("\n")
      : "  - (none declared — keep changes minimal and justify anything outside expected scope)"
  const inputLines =
    task.contract.inputs.length > 0
      ? task.contract.inputs.map((input) => `  - ${input}`).join("\n")
      : "  - (none)"
  const outputLines =
    task.contract.outputs.length > 0
      ? task.contract.outputs.map((output) => `  - ${output}`).join("\n")
      : "  - (none)"

  return [
    `# BOOT BRIEF — ${task.id}`,
    "",
    `**ROLE:** ${task.role} agent — one PR, one branch, nothing else.`,
    `**PARENT BRANCH:** \`${ctx.parent}\` — the ONLY branch your PR may target.`,
    `**WORKTREE:** \`${ctx.worktreePath}\` (branch \`${branch}\` checked out; install done).`,
    "",
    "## Repo context",
    `- Project root: \`${ctx.repoRoot}\` — read \`AGENTS.md\` (mandatory) and \`HAMILTON.md\` first.`,
    "",
    "## Worktree (already set up — do NOT create or switch branches)",
    `- Work ONLY inside: \`${ctx.worktreePath}\`.`,
    `- Commit inside this worktree; push ONLY \`${branch}\` when done: \`git push origin ${branch}\` (run from the worktree).`,
    "- Never touch any other branch, never merge, never squash, never touch remote history, never work in the main repo directory.",
    "",
    "## File zone (preferred scope — soft guidance)",
    "- Aim your changes at the zone below; try not to change a lot of things, especially unrelated things, outside it. If a change outside the zone is genuinely necessary, make it minimal and justify it in the PR body.",
    "- Zones are descriptive, not punitive.",
    "- Zone entries:",
    zoneLines,
    "",
    "## Task contract",
    "### Inputs (read these first)",
    inputLines,
    "### Outputs (produce these)",
    outputLines,
    "",
    "## PR title (final squash message)",
    `\`${prTitle}\``,
    "",
    "## Model & subagents",
    `- Model: \`${task.model}\`.`,
    `- Allowed subagents: ${task.allowed_subagents.length > 0 ? task.allowed_subagents.join(", ") : "none — work alone unless the task requires it"}.`,
    "",
    "## Reporting (mandatory protocol — Hamilton MCP tools)",
    "- `heartbeat` — report liveness on schedule; the orchestrator treats silence as stalled.",
    "- `checkpoint` — phase + message (+ files) at every milestone: claimed, started, each file completed, each test green, each commit.",
    "- `ready_for_review` — declare done with a summary, branch, and check results.",
    "- Report every error (impact + recovery) and every hard blocker (BLOCKED + a file in `.agent-state/questions/`).",
    "",
    "## Safety (non-negotiable)",
    "- Work in your own worktree only; never `git checkout`/`git switch`; never touch another worktree's files.",
    "- Push only your own branch; no force-push, no rebase, no remote-history edits on any branch but your own.",
    "- Many small commits — one logical unit per commit, each reported via checkpoint.",
    "- Never `git add -A` or `git add .` — stage only files within your zone.",
    "- Version bumps: changesets PATCH-only via `pnpm changeset`; never edit `package.json` versions by hand.",
    "",
    "## Checks (all must pass before done)",
    "1. `pnpm typecheck`",
    "2. `pnpm format:check`",
    "3. `pnpm test`",
    "4. pre-commit hooks",
    "",
    "## Done = ready_for_review",
    "- Push the branch, ensure the checks pass, then emit `ready_for_review` via the MCP tool with a summary of changes. Do NOT merge — the conductor reviews and prepares the merge for the owner.",
    "",
  ].join("\n")
}

// ---------------------------------------------------------------------------
// 4. LLM-assisted decomposition (injectable; the only non-deterministic part)
// ---------------------------------------------------------------------------

export interface Decomposer {
  decompose(prompt: string): Promise<unknown>
}

export const DECOMPOSE_PROMPT = `You are the Hamilton planner for the project %%PROJECT%%.

First, check which repo context files exist (HAMILTON.md, FEATURES.md, ROADMAP.md, AGENTS.md) and note their existence to yourself. Do NOT paste their contents.

Then decompose the user request below into a task DAG. Each task MUST conform to this schema:

- id: unique string (e.g. "t1", "wa-motion-schema")
- role: "implementer" | "planner" | "reviewer" | "docs"
- zone: array of path globs the task is expected to touch
- depends_on: array of task ids that must complete first (empty array for root tasks)
- status: "planned"
- on_failure: "retry-once" | "skip" | "escalate"
- contract: { inputs: [string], outputs: [string] } — inputs are the doc/file references the task reads; outputs are the concrete artifacts it produces
- model: "provider/model"
- allowed_subagents: array of subagent role names (empty array if none)
- budget_cap: optional number
- branch: optional "feat/<taskId>"
- pr_title: optional conventional-commit title

Split the work into independent tasks where possible; wire dependencies through depends_on only; do not invent tasks that do not serve the request.

Return ONLY valid JSON with this exact shape — no markdown fences, no commentary, no trailing text:

{"tasks": [...]}

User request:
%%REQUEST%%`

function plannerModelRef(raw: string | undefined): ModelRef | undefined {
  if (raw === undefined || raw === "") return undefined
  const slash = raw.indexOf("/")
  if (slash === -1) return { providerID: "opencode", id: raw }
  return { providerID: raw.slice(0, slash), id: raw.slice(slash + 1) }
}

export function decomposeWithOpencode(
  controlPlane: ControlPlane,
  projectName: string,
): Decomposer {
  return {
    async decompose(prompt: string): Promise<unknown> {
      const model = plannerModelRef(process.env.HAMILTON_PLANNER_MODEL)
      const created = await controlPlane.client.v2.session.create({
        agent: "plan",
        ...(model !== undefined ? { model } : {}),
      })
      const sessionID = created.data?.data?.id
      if (sessionID === undefined) {
        throw new Error(
          "opencode control plane did not return a session id (is `opencode serve` running?)",
        )
      }
      logger.info("planner session created", { sessionID })

      const text = DECOMPOSE_PROMPT.replace("%%PROJECT%%", projectName).replace(
        "%%REQUEST%%",
        prompt,
      )
      const result = await controlPlane.client.v2.session.prompt({
        sessionID,
        prompt: { text },
        delivery: "steer",
      })
      if (result.data === undefined) {
        throw new Error(
          "opencode control plane did not admit the decomposition prompt",
        )
      }
      return result.data.data
    },
  }
}

function validationError(issues: string[]): Error {
  const shown = issues.slice(0, 5)
  const rest = issues.length - shown.length
  const suffix = rest > 0 ? ` (+${rest} more)` : ""
  return new Error(`plan failed validation: ${shown.join("; ")}${suffix}`)
}

export async function planFromPrompt(
  prompt: string,
  decomposer: Decomposer,
): Promise<TaskGraph> {
  const raw = await decomposer.decompose(prompt)
  const result = validateGraph(raw)
  if (!result.ok) {
    throw validationError(result.issues)
  }
  logger.info("plan validated", { tasks: result.graph.tasks.length })
  return normalizeGraph(result.graph)
}

// Plans load as JSON (graph.yaml is a projection, not the canonical input).
// JSON parse failures and validation failures both throw with the file path.
export function planFromFile(path: string): TaskGraph {
  let raw: unknown
  try {
    raw = JSON.parse(readFileSync(path, "utf8"))
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error)
    throw new Error(`cannot read plan file '${path}': ${detail}`, {
      cause: error,
    })
  }
  const result = validateGraph(raw)
  if (!result.ok) {
    throw new Error(
      `plan file '${path}': ${validationError(result.issues).message}`,
    )
  }
  return normalizeGraph(result.graph)
}
