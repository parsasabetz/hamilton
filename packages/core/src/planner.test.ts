import { describe, expect, test } from "bun:test"
import { mkdtempSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import type { Task, TaskGraph } from "@hamilton/shared"
import type { Decomposer } from "./planner.ts"
import {
  normalizeGraph,
  planFromFile,
  planFromPrompt,
  renderBrief,
  renderGraphYaml,
  validateGraph,
} from "./planner.ts"

function task(overrides: Partial<Task> = {}): Task {
  return {
    id: "t1",
    role: "implementer",
    zone: ["packages/core/src"],
    depends_on: [],
    status: "planned",
    on_failure: "retry-once",
    contract: { inputs: ["doc §1"], outputs: ["feature"] },
    model: "opencode-go/deepseek-v4-flash",
    allowed_subagents: [],
    ...overrides,
  }
}

function graph(tasks: Task[]): TaskGraph {
  return { tasks }
}

describe("validateGraph", () => {
  test("accepts a valid graph", () => {
    const result = validateGraph(graph([task()]))
    expect(result).toEqual({ ok: true, graph: { tasks: [task()] } })
  })

  test("rejects a depends_on referencing a missing task id", () => {
    const result = validateGraph(graph([task({ depends_on: ["ghost"] })]))
    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.issues).toEqual([
        "task t1: depends on missing task 'ghost'",
      ])
    }
  })

  test("rejects a dependency cycle with its path", () => {
    const result = validateGraph(
      graph([
        task({ id: "t1", depends_on: ["t2"] }),
        task({ id: "t2", depends_on: ["t1"] }),
      ]),
    )
    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.issues).toEqual(["cycle: t1 -> t2 -> t1"])
    }
  })

  test("rejects a self-cycle", () => {
    const result = validateGraph(graph([task({ depends_on: ["t1"] })]))
    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.issues).toEqual(["cycle: t1 -> t1"])
    }
  })

  test("reports zod issues with their path", () => {
    const result = validateGraph({ tasks: [{ ...task(), role: "bogus" }] })
    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(result.issues[0]).toContain("tasks[0].role")
    }
  })

  test("reports missing required fields with bracketed paths", () => {
    const result = validateGraph({ tasks: [{}] })
    expect(result.ok).toBe(false)
    if (!result.ok) {
      expect(
        result.issues.some((issue) => issue.startsWith("tasks[0].id:")),
      ).toBe(true)
    }
  })
})

describe("normalizeGraph", () => {
  test("assigns feat/<id> as branch when missing", () => {
    const normalized = normalizeGraph(graph([task(), task({ id: "t2" })]))
    expect(normalized.tasks[0]?.branch).toBe("feat/t1")
    expect(normalized.tasks[1]?.branch).toBe("feat/t2")
  })

  test("leaves a provided branch untouched", () => {
    const normalized = normalizeGraph(graph([task({ branch: "custom/x" })]))
    expect(normalized.tasks[0]?.branch).toBe("custom/x")
  })

  test("does not touch status or optional fields", () => {
    const normalized = normalizeGraph(
      graph([task({ status: "optional", budget_cap: 7 })]),
    )
    expect(normalized.tasks[0]?.status).toBe("optional")
    expect(normalized.tasks[0]?.budget_cap).toBe(7)
  })
})

describe("renderGraphYaml", () => {
  test("renders the fixed shape with two-space indentation", () => {
    const yaml = renderGraphYaml(
      normalizeGraph(graph([task({ pr_title: "feat(t1): feature" })])),
    )
    expect(yaml).toBe(`# Task DAG — generated by Hamilton planner (M2)
tasks:
  - id: t1
    role: implementer
    zone:
      - packages/core/src
    depends_on: []
    status: planned
    on_failure: retry-once
    contract:
      inputs:
        - "doc §1"
      outputs:
        - "feature"
    model: opencode-go/deepseek-v4-flash
    allowed_subagents: []
    branch: feat/t1
    pr_title: "feat(t1): feature"
`)
  })

  test("quotes values containing ': '", () => {
    const yaml = renderGraphYaml(
      graph([task({ pr_title: "feat(t1): feature" })]),
    )
    expect(yaml).toContain('pr_title: "feat(t1): feature"')
  })

  test("omits budget_cap when undefined", () => {
    const yaml = renderGraphYaml(graph([task()]))
    expect(yaml).not.toContain("budget_cap")
  })

  test("emits budget_cap when present", () => {
    const yaml = renderGraphYaml(graph([task({ budget_cap: 50 })]))
    expect(yaml).toContain("budget_cap: 50")
  })

  test("renders non-empty arrays as block lists in task order", () => {
    const yaml = renderGraphYaml(
      graph([
        task({
          id: "t1",
          zone: ["a", "b"],
          depends_on: ["t2"],
          contract: { inputs: ["i1"], outputs: ["o1"] },
          pr_title: undefined,
        }),
        task({ id: "t2" }),
      ]),
    )
    expect(yaml).toContain("    depends_on:\n      - t2")
    expect(yaml).toContain("    zone:\n      - a\n      - b")
    expect(yaml.indexOf("  - id: t1")).toBeLessThan(yaml.indexOf("  - id: t2"))
  })

  test("is deterministic — identical graph renders identically", () => {
    const g = normalizeGraph(graph([task()]))
    expect(renderGraphYaml(g)).toBe(renderGraphYaml(g))
  })
})

describe("renderBrief", () => {
  const ctx = {
    repoRoot: "/repo",
    parent: "main",
    worktreePath: "/repo/.worktrees/t1",
  }

  test("contains task id, parent, worktree, and zone", () => {
    const brief = renderBrief(task(), ctx)
    expect(brief).toContain("# BOOT BRIEF — t1")
    expect(brief).toContain("`main`")
    expect(brief).toContain("/repo/.worktrees/t1")
    expect(brief).toContain("- `packages/core/src`")
  })

  test("contains contract inputs and outputs", () => {
    const brief = renderBrief(task(), ctx)
    expect(brief).toContain("doc §1")
    expect(brief).toContain("- feature")
  })

  test("contains the reporting protocol and safety rules", () => {
    const brief = renderBrief(task(), ctx)
    expect(brief).toContain("ready_for_review")
    expect(brief).toContain("no force-push")
    expect(brief).toContain("git add -A")
    expect(brief).toContain("PATCH-only")
  })

  test("derives pr title from the first output word when absent", () => {
    const brief = renderBrief(task(), ctx)
    expect(brief).toContain("feat(t1): feature")
  })

  test("uses the task's own pr_title when present", () => {
    const brief = renderBrief(task({ pr_title: "feat(t1): custom title" }), ctx)
    expect(brief).toContain("feat(t1): custom title")
  })
})

describe("planFromPrompt", () => {
  test("valid decomposition returns a normalized graph", async () => {
    const decomposer: Decomposer = {
      decompose: async () => graph([task()]),
    }
    const plan = await planFromPrompt("build the thing", decomposer)
    expect(plan.tasks[0]?.branch).toBe("feat/t1")
    expect(plan.tasks[0]?.status).toBe("planned")
  })

  test("invalid decomposition throws with issue text", async () => {
    const decomposer: Decomposer = {
      decompose: async () => ({ tasks: [{ ...task(), role: "bogus" }] }),
    }
    await expect(planFromPrompt("x", decomposer)).rejects.toThrow(
      /tasks\[0\]\.role/,
    )
  })

  test("lists the first five issues and counts the rest", async () => {
    const tasks = Array.from({ length: 7 }, (_, i) =>
      task({ id: `t${i}`, depends_on: ["ghost"] }),
    )
    const decomposer: Decomposer = { decompose: async () => graph(tasks) }
    await expect(planFromPrompt("x", decomposer)).rejects.toThrow(
      /task t0: depends on missing task 'ghost'.*task t4: depends on missing task 'ghost' \(\+2 more\)/,
    )
  })
})

describe("planFromFile", () => {
  test("parses, validates, and normalizes a JSON plan", () => {
    const dir = mkdtempSync(join(tmpdir(), "hamilton-planner-"))
    try {
      const path = join(dir, "plan.json")
      writeFileSync(path, JSON.stringify(graph([task()])))
      const plan = planFromFile(path)
      expect(plan.tasks[0]?.branch).toBe("feat/t1")
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("throws a clear message on invalid JSON", () => {
    const dir = mkdtempSync(join(tmpdir(), "hamilton-planner-"))
    try {
      const path = join(dir, "plan.json")
      writeFileSync(path, "not json {")
      expect(() => planFromFile(path)).toThrow(/cannot read plan file/)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })

  test("throws a clear message on an invalid plan", () => {
    const dir = mkdtempSync(join(tmpdir(), "hamilton-planner-"))
    try {
      const path = join(dir, "plan.json")
      writeFileSync(path, JSON.stringify({ tasks: [{ id: "t1" }] }))
      expect(() => planFromFile(path)).toThrow(/plan file .* failed validation/)
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
