/**
 * Compact description of one zod schema: "string", "enum[a, b]", "string[]",
 * "object". Duck-typed over the schema's internal def (zod v4 `type` keys with
 * v3-style fallbacks) so we never depend on zod internals beyond what the
 * specs expose; anything unreadable falls back to "object".
 */
function describeZodType(schema: unknown): string {
  if (typeof schema !== "object" || schema === null) return "object"
  try {
    const def = (schema as Record<string, unknown>)["_def"]
    if (typeof def !== "object" || def === null) return "object"
    const record = def as Record<string, unknown>
    const kind =
      typeof record["type"] === "string"
        ? (record["type"] as string)
        : undefined
    switch (kind) {
      case "string":
        return "string"
      case "boolean":
        return "boolean"
      case "number":
        return "number"
      case "enum": {
        const raw = record["entries"] ?? record["values"]
        const values = Array.isArray(raw)
          ? raw
          : typeof raw === "object" && raw !== null
            ? Object.keys(raw as Record<string, unknown>)
            : []
        return values.length > 0 ? `enum[${values.join(", ")}]` : "string"
      }
      case "array": {
        const element = record["element"] ?? record["elementType"]
        return `${describeZodType(element)}[]`
      }
      case "optional":
      case "default":
        return describeZodType(record["innerType"])
      default:
        return "object"
    }
  } catch {
    return "object"
  }
}

/**
 * Describe a tool's inputSchema shape as "key: type, key?: type" — optionals
 * get a "?" suffix on the key (the guidelines' table style).
 */
export function describeSchema(schema: unknown): string {
  if (typeof schema !== "object" || schema === null) return "object"
  try {
    const shape = (schema as { shape?: unknown }).shape
    if (typeof shape !== "object" || shape === null) return "object"
    const parts: string[] = []
    for (const [key, zodType] of Object.entries(
      shape as Record<string, unknown>,
    )) {
      const isOptional =
        typeof zodType === "object" &&
        zodType !== null &&
        typeof (zodType as { isOptional?: () => boolean }).isOptional ===
          "function" &&
        (zodType as { isOptional: () => boolean }).isOptional()
      parts.push(`${key}${isOptional ? "?" : ""}: ${describeZodType(zodType)}`)
    }
    return parts.length > 0 ? parts.join(", ") : "object"
  } catch {
    return "object"
  }
}

/** The full agent-facing tool table, rendered from the live hamiltonToolSpecs. */
export function renderToolTable(): string {
  const rows = hamiltonToolSpecs.map((spec) => {
    const params = describeSchema(spec.inputSchema)
    return `| ${spec.name} | ${params} | ${spec.description} |`
  })
  return [
    "| tool | params | what it does |",
    "| --- | --- | --- |",
    ...rows,
  ].join("\n")
}

/** The checkpoint phase → status matrix, rendered from the live contract. */
function renderCheckpointMatrix(): string {
  return Object.entries(checkpointPhaseStatus)
    .map(([phase, statuses]) => `${phase} → ${statuses.join(", ")}`)
    .join("\n")
}

